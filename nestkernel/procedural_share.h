/*
 * EXPERIMENTAL, NOT STOCK NEST (regenerated connections, Stage A).
 *
 * How many of a projection's connections on one virtual process leave each source, regenerated instead of stored.
 * NEST's fixed_total_number draws each of a process's K connections with a source uniform over the n sources, so the
 * counts per source are Multinomial(K; 1/n). They are regenerated by a binary tree of binomial splits over the sources,
 * as the prototype engine does: node 1 spans the sources [0, n); node v over [lo, hi) splits at mid = lo + (hi - lo) / 2
 * into 2v and 2v + 1, the left count Binomial(count, (mid - lo) / (hi - lo)), keyed by (projection, node, process).
 * The upper levels are kept; a source's count is then a few splits away. Independent of the rest of NEST.
 */

#ifndef PROCEDURAL_SHARE_H
#define PROCEDURAL_SHARE_H

// C++ includes:
#include <cstddef>
#include <cstdint>
#include <vector>

// Includes from nestkernel:
#include "procedural_random.h"

namespace nest
{

class ProceduralShareTree
{
public:
  using Key = ProceduralWords::Philox::key_type;

  /**
   * @param key (seed, projection)
   * @param vp the virtual process whose share this is
   * @param sources n, the number of sources
   * @param total K, the process's connections of this projection
   * @param cache nodes spanning at least this many sources are kept (the engine keeps 256)
   */
  ProceduralShareTree( const Key& key,
    const std::uint64_t vp,
    const std::uint64_t sources,
    const std::uint64_t total,
    const std::uint64_t cache = 256 )
    : key_( key )
    , vp_( vp )
    , sources_( sources )
  {
    while ( ( sources_ >> ( depth_ + 1 ) ) >= cache )
    {
      ++depth_;
    }
    const std::size_t nodes = std::size_t { 2 } << depth_;
    counts_.assign( nodes, 0 );
    std::vector< std::uint64_t > lo( nodes, 0 );
    std::vector< std::uint64_t > hi( nodes, sources_ );
    counts_[ 1 ] = total;
    for ( std::uint64_t v = 1; v < ( std::uint64_t { 1 } << depth_ ); ++v )
    {
      const std::uint64_t mid = lo[ v ] + ( hi[ v ] - lo[ v ] ) / 2;
      const std::uint64_t left = left_share_( v, counts_[ v ], lo[ v ], mid, hi[ v ] );
      counts_[ 2 * v ] = left;
      counts_[ 2 * v + 1 ] = counts_[ v ] - left;
      lo[ 2 * v ] = lo[ v ];
      hi[ 2 * v ] = mid;
      lo[ 2 * v + 1 ] = mid;
      hi[ 2 * v + 1 ] = hi[ v ];
    }
  }

  //! The number of connections that leave source s (its index among the sources).
  std::uint64_t
  share( const std::uint64_t s ) const
  {
    std::uint64_t lo = 0;
    std::uint64_t hi = sources_;
    std::uint64_t v = 1;
    for ( std::uint32_t d = 0; d < depth_; ++d )
    {
      const std::uint64_t mid = lo + ( hi - lo ) / 2;
      if ( s < mid )
      {
        v = 2 * v;
        hi = mid;
      }
      else
      {
        v = 2 * v + 1;
        lo = mid;
      }
    }
    std::uint64_t count = counts_[ v ];
    while ( hi - lo > 1 and count > 0 )
    {
      const std::uint64_t mid = lo + ( hi - lo ) / 2;
      const std::uint64_t left = left_share_( v, count, lo, mid, hi );
      if ( s < mid )
      {
        v = 2 * v;
        hi = mid;
        count = left;
      }
      else
      {
        v = 2 * v + 1;
        lo = mid;
        count -= left;
      }
    }
    return count;
  }

  /**
   * Calls use( s, count ) for every source with connections, in increasing order of s: one walk over the tree's
   * non-empty branches, splitting as share() does, so the counts are the same, at a cost that grows with the total
   * rather than with the number of sources.
   */
  template < typename F >
  void
  for_each_nonzero( F&& use ) const
  {
    struct Branch
    {
      std::uint64_t v, lo, hi, count;
      std::uint32_t depth;
    };
    std::vector< Branch > stack { Branch { 1, 0, sources_, counts_[ 1 ], 0 } };
    while ( not stack.empty() )
    {
      const Branch b = stack.back();
      stack.pop_back();
      if ( b.count == 0 )
      {
        continue;
      }
      if ( b.hi - b.lo == 1 )
      {
        use( b.lo, b.count );
        continue;
      }
      const std::uint64_t mid = b.lo + ( b.hi - b.lo ) / 2;
      const std::uint64_t left = b.depth < depth_ ? counts_[ 2 * b.v ] : left_share_( b.v, b.count, b.lo, mid, b.hi );
      stack.push_back( Branch { 2 * b.v + 1, mid, b.hi, b.count - left, b.depth + 1 } ); // the right half after the left
      stack.push_back( Branch { 2 * b.v, b.lo, mid, left, b.depth + 1 } );
    }
  }

  //! The kept counts' memory, in bytes.
  std::size_t
  bytes() const
  {
    return counts_.size() * sizeof( std::uint64_t );
  }

private:
  std::uint64_t
  left_share_( const std::uint64_t node,
    const std::uint64_t count,
    const std::uint64_t lo,
    const std::uint64_t mid,
    const std::uint64_t hi ) const
  {
    ProceduralWords w( key_, procedural_counter( ProceduralStream::share, node, 0, vp_ ) );
    return procedural_binomial( count, static_cast< double >( mid - lo ) / static_cast< double >( hi - lo ), w );
  }

  Key key_;
  std::uint64_t vp_;
  std::uint64_t sources_;
  std::uint32_t depth_ = 0;
  std::vector< std::uint64_t > counts_;
};

} // namespace nest

#endif /* #ifndef PROCEDURAL_SHARE_H */
